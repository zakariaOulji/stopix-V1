const pad2 = (n: number) => String(n).padStart(2, '0');

/** Deterministic scatter of `count` stops around a center, with a given status. */
function generateStops(
  tourneeId: string,
  count: number,
  center: { latitude: number; longitude: number },
  status: Stop['status'],
  startHour: number,
): Stop[] {
  return Array.from({ length: count }).map((_, i) => {
    const angle = i * 2.39996; // golden-angle spiral for an even spread
    const dist = 0.004 + (i % 5) * 0.0016;
    const minutes = startHour * 60 + i * 14;
    const eta = `${pad2(Math.floor(minutes / 60))}:${pad2(minutes % 60)}`;
    return {
      id: `${tourneeId}-stop-${i + 1}`,
      tourneeId,
      order: i + 1,
      status,
      recipient: RECIPIENTS[i % RECIPIENTS.length],
      address: `${3 + ((i * 7) % 90)} ${STREETS[i % STREETS.length]}`,
      city: 'Paris',
      postalCode: tourneeId === 'tournee-done' ? '75012' : '75020',
      lat: center.latitude + Math.sin(angle) * dist,
      lng: center.longitude + Math.cos(angle) * dist,
      packages: 1 + (i % 3),
      eta,
      ...(status === 'delivered' ? { completedAt: eta } : {}),
      ...(i % 4 === 0 ? { accessCode: `${String.fromCharCode(65 + (i % 26))}${1000 + i}` } : {}),
    } satisfies Stop;
  });
}

